import { expect, type Page, type TestInfo } from "@playwright/test";

export async function phoneContentJourney(page: Page, info: TestInfo, capture: (page: Page, info: TestInfo, name: string) => Promise<void>) {
  const original = page.viewportSize()!;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/workflows/activity-definitions");
  await page.locator(".studio-page-header").getByRole("button", { name: "Create activity", exact: true }).click();
  await page.getByRole("textbox", { name: "Display name", exact: true }).fill(`Phone authoring ${info.project.name} ${Date.now()}`);
  await page.locator("label.wf-root-card").filter({ has: page.getByRole("radio", { name: "Sequence", exact: true }) }).click();
  await page.getByRole("button", { name: "Create definition", exact: true }).click();
  await expect(page.getByRole("region", { name: "Provider implementation editor", exact: true })).toBeVisible();
  const editorUrl = page.url();
  const canvas = page.locator(".ad-graph-canvas");
  const expectCanvas = async () => expect.poll(async () => (await canvas.boundingBox())!.width).toBeGreaterThanOrEqual(260);
  await expect(page.getByRole("button", { name: "Expand inspector panel", exact: true })).toBeVisible();
  await expectCanvas();
  await capture(page, info, "phone-authoring-entry");
  await page.reload(); await expectCanvas();
  await page.getByRole("button", { name: "Expand inspector panel", exact: true }).press("Enter");
  await capture(page, info, "phone-inspector");
  await page.getByRole("button", { name: "Maximize inspector panel", exact: true }).click();
  await expect(page.getByRole("button", { name: "Restore inspector panel", exact: true })).toBeVisible();
  await capture(page, info, "phone-inspector-maximized");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "Collapse inspector panel", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Collapse inspector panel", exact: true }).click();
  await expectCanvas();
  await page.getByRole("button", { name: "Expand activities panel", exact: true }).press("Enter");
  const search = page.getByRole("searchbox", { name: "Search activity palette", exact: true });
  await search.fill("Write");
  await capture(page, info, "phone-activities");
  await page.getByRole("button", { name: "Collapse activities panel", exact: true }).click();
  await expectCanvas();
  for (const width of [768, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    await expect(page.getByRole("button", { name: "Collapse inspector panel", exact: true })).toBeVisible();
    await expectCanvas();
    await capture(page, info, `authoring-${width}`);
  }
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto(editorUrl); await expectCanvas();

  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto("/settings/theme-builder");
  const sections = page.getByRole("navigation", { name: "Settings sections", exact: true });
  await sections.getByRole("link", { name: "Theme Builder", exact: true }).focus();
  await page.setViewportSize({ width: 390, height: 844 });
  const sectionSelect = page.getByRole("combobox", { name: "Settings section", exact: true });
  await expect(sectionSelect).toBeFocused();
  const theme = page.locator(".theme-builder-page:visible");
  const themeSelect = theme.getByRole("combobox", { name: "Current theme", exact: true });
  await expect(themeSelect).toBeVisible();
  await expect(theme.locator(".theme-builder-list")).toHaveCount(0);
  expect((await theme.locator(".theme-builder-detail").boundingBox())!.y).toBeLessThan(844);
  await capture(page, info, "phone-theme-entry");
  await theme.getByRole("button", { name: "Duplicate", exact: true }).click();
  const name = theme.getByRole("textbox", { name: "Name", exact: true });
  await expect(name).toBeEditable();
  const selectedId = await themeSelect.inputValue();
  const edited = `Retained phone theme ${info.project.name} with a long name`;
  await name.fill(edited);
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(name).toHaveValue(edited); await expect(name).toBeFocused();
  await capture(page, info, "theme-desktop-dirty");
  await theme.getByRole("tab", { name: "Tokens", exact: true }).click();
  const primary = theme.getByRole("textbox", { name: "primary", exact: true });
  await primary.fill("oklch(0.5 0.15 250)");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(primary).toHaveValue("oklch(0.5 0.15 250)"); await expect(primary).toBeFocused();
  await expect(themeSelect).toHaveValue(selectedId);
  await capture(page, info, "phone-theme-dirty");
  await themeSelect.focus(); await page.setViewportSize({ width: 1280, height: 900 });
  await expect(theme.locator(".theme-builder-list button.active")).toBeFocused();
  await theme.getByRole("tab", { name: "Overview", exact: true }).click();
  await expect(name).toHaveValue(edited);
  await theme.getByRole("button", { name: "Save", exact: true }).click();
  await expect(theme.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 }); await page.reload();
  await expect(themeSelect).toBeVisible(); await themeSelect.selectOption(selectedId);
  await expect(name).toHaveValue(edited);
  await theme.getByRole("tab", { name: "Tokens", exact: true }).click();
  await expect(primary).toHaveValue("oklch(0.5 0.15 250)");
  await capture(page, info, "phone-theme-reopened");
  await theme.getByRole("button", { name: "Delete", exact: true }).click();
  await page.getByRole("dialog", { name: "Delete theme", exact: true }).getByRole("button", { name: "Delete theme", exact: true }).click();
  await expect(themeSelect).not.toHaveValue(selectedId);
  await sectionSelect.selectOption({ label: "Features" });
  await expect(page.getByRole("heading", { name: "Features", exact: true })).toBeVisible();
  await capture(page, info, "phone-settings-navigation");
  await page.setViewportSize(original);
}
