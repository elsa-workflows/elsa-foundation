using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Elsa.Workflows.Design.CodeGeneration;

/// <summary>
/// Incremental-generator entry point for the code-first activity-call facade.
/// </summary>
/// <remarks>
/// The marker emitted here keeps the new Roslyn project independently buildable while the activity-contract
/// discovery and facade emission slices are implemented. It deliberately has no dependency on runtime packages.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class ActivityCallGenerator : IIncrementalGenerator
{
    public const string GeneratedHintName = "ElsaActivityCallGenerator.g.cs";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output => output.AddSource(
            GeneratedHintName,
            SourceText.From(
                "// <auto-generated/>\nnamespace Elsa.Workflows.Design.CodeGeneration.Generated;\ninternal static class ElsaActivityCallGeneratorMarker { }\n",
                Encoding.UTF8)));
    }
}
