function qualifiedName(namespaceURI: string | null, localName: string): string | undefined {
  const prefix = namespaceURI !== null && Object.hasOwn(namespacePrefixes, namespaceURI) ? namespacePrefixes[namespaceURI] : undefined;
  return prefix === undefined ? undefined : prefix + localName;
}
function validNcName(element: Element, value: string): boolean {
  if (!value || value.includes(":")) return false;
  try { element.ownerDocument.createElement(value); return true; } catch { return false; }
}
function xsiTypeName(element: Element, value: string): string | undefined {
  const parts = value.trim().split(":");
  if (parts.length > 2 || parts.some(part => !validNcName(element, part))) return undefined;
  return qualifiedName(element.lookupNamespaceURI(parts.length === 2 ? parts[0] : null), parts.at(-1)!);
}
function derivesFrom(type: string, base: string): boolean {
  for (let current: string | null | undefined = type; current; current = typeBases[current])
    if (current === base) return true;
  return false;
}
function declaredType(element: Element, parentType: string | undefined): string | undefined {
  const name = qualifiedName(element.namespaceURI, element.localName);
  if (!name || abstractElements.has(name)) return undefined;
  for (let current: string | null | undefined = parentType; current; current = typeBases[current]) {
    const properties = localElementTypes[current];
    if (properties && Object.hasOwn(properties, name)) return properties[name];
  }
  return Object.hasOwn(globalElementTypes, name) ? globalElementTypes[name] : undefined;
}
function effectiveType(element: Element): string | undefined {
  let parentType: string | undefined;
  if (element.parentElement) {
    parentType = effectiveType(element.parentElement);
    // Opaque content cannot acquire standard ownership from a standard-looking descendant.
    if (!parentType || opaqueContentTypes.has(parentType)) return undefined;
  }
  const declared = declaredType(element, parentType);
  if (!declared) return undefined;
  const explicit = element.getAttributeNS("http://www.w3.org/2001/XMLSchema-instance", "type");
  if (explicit === null) return declared;
  const type = xsiTypeName(element, explicit);
  return type && Object.hasOwn(typeBases, type) && !abstractTypes.has(type) && derivesFrom(type, declared) ? type : undefined;
}

export function standardBpmnReferenceContext(element: Element): boolean {
  const type = effectiveType(element);
  return type !== undefined && !["tExtensionElements", "tDocumentation", "tScript", "tText"].includes(type);
}

export function standardBpmnReferenceAttribute(element: Element, attribute: Attr): boolean {
  if (attribute.namespaceURI) return false;
  for (let type: string | null | undefined = effectiveType(element); type; type = typeBases[type])
    if (referenceAttributes[type]?.includes(attribute.localName)) return true;
  return false;
}

export function standardBpmnReferenceText(element: Element): boolean {
  const type = effectiveType(element);
  return type === "xsd:QName" || type === "xsd:IDREF";
}
