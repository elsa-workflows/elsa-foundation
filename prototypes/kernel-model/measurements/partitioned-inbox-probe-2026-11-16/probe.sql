\set ON_ERROR_STOP off
select version();
-- A: current shape, list/range by Partition, current key (Id, InboxScope)
create table a(id text, scope bigint, part int, seq bigint generated by default as identity, done bool default false, primary key (id, scope)) partition by range (part);
-- B: key extended with the partition
create table b(id text, scope bigint, part int, seq bigint generated by default as identity, done bool default false, primary key (part, id, scope)) partition by range (part);
create table b0 partition of b for values from (0) to (32);
create table b1 partition of b for values from (32) to (64);
insert into b(id,scope,part) values ('m1',0,1) on conflict (part,id,scope) do nothing;
insert into b(id,scope,part) values ('m1',0,40) on conflict (part,id,scope) do nothing;
select 'B same id in two partitions:' , count(*) from b where id='m1';
insert into b(id,scope,part) values ('m1',0,1) on conflict (id,scope) do nothing;
-- C: hash on Id keeps the current key
create table c(id text, scope bigint, part int, seq bigint generated by default as identity, done bool default false, primary key (id, scope)) partition by hash (id);
create table c0 partition of c for values with (modulus 4, remainder 0);
create table c1 partition of c for values with (modulus 4, remainder 1);
create table c2 partition of c for values with (modulus 4, remainder 2);
create table c3 partition of c for values with (modulus 4, remainder 3);
create index on c(part, seq);
insert into c(id,scope,part) select 'x'||g,0,g%8 from generate_series(1,2000) g;
insert into c(id,scope,part) values ('x1',0,3) on conflict (id,scope) do nothing;
select 'C dedup ok, rows with x1:', count(*) from c where id='x1';
analyze c;
set enable_seqscan=off;
explain (costs off) select id from c where part=3 and done=false order by seq limit 10;
explain (costs off) select id from c where id='x7' and scope=0;
-- B pruning for poll
insert into b(id,scope,part) select 'y'||g,0,g%64 from generate_series(1,2000) g;
create index on b(part,seq);
analyze b;
explain (costs off) select id from b where part=3 and done=false order by seq limit 10;
