using System.Text.Json;

namespace Elsa3.Mapping.ActivityMap;

/// <summary>Vocabulary the built-in table is written in: one helper per member-map rule.</summary>
internal sealed partial class Elsa3BuiltInActivityMap
{
    private static Elsa3ActivityMapEntry Catalog(
        string elsa3Type,
        string activityTypeKey,
        Elsa3MemberRule[] members,
        Elsa3OutcomeRule[]? outcomes = null,
        Elsa3NodeRewriteKind? rewrite = null,
        params string[] warnings) =>
        new($"Elsa.{elsa3Type}", new Elsa3ActivityTarget.CatalogActivity(activityTypeKey), members, outcomes ?? [], rewrite, warnings);

    private static Elsa3ActivityMapEntry Intrinsic(
        string elsa3Type,
        string activityVersionId,
        Elsa3MemberRule[] members,
        Elsa3NodeRewriteKind? rewrite = null) =>
        new($"Elsa.{elsa3Type}", new Elsa3ActivityTarget.Intrinsic(activityVersionId), members, [], rewrite);

    private static Elsa3ActivityMapEntry GraphConstruct(string elsa3Type, Elsa3GraphConstructKind kind, params Elsa3MemberRule[] members) =>
        new($"Elsa.{elsa3Type}", new Elsa3ActivityTarget.GraphConstruct(kind), members, []);

    private static Elsa3ActivityMapEntry NoCounterpart(string elsa3Type, string reason, params Elsa3MemberRule[] members) =>
        new($"Elsa.{elsa3Type}", new Elsa3ActivityTarget.NoCounterpart(reason), members, []);

    /// <summary>R1: the same input, or a rename.</summary>
    private static Elsa3MemberRule Carry(string elsa3, string elsa4Key, string? warning = null) =>
        new(elsa3, Elsa3MemberKind.Input, Elsa3MemberRuleKind.Carry, elsa4Key, BehaviourWarning: warning);

    /// <summary>R1: the same output, or a rename.</summary>
    private static Elsa3MemberRule CarryOutput(string elsa3, string elsa4Key, string? warning = null) =>
        new(elsa3, Elsa3MemberKind.Output, Elsa3MemberRuleKind.Carry, elsa4Key, BehaviourWarning: warning);

    /// <summary>R1: an Elsa 3 port carried into an Elsa 4 child slot.</summary>
    private static Elsa3MemberRule Slot(string elsa3, string slotName) =>
        new(elsa3, Elsa3MemberKind.Port, Elsa3MemberRuleKind.ChildSlot, slotName);

    /// <summary>R2: emit the Elsa 3 effective value when the node leaves the member unset.</summary>
    private static Elsa3MemberRule DefaultFlip(string elsa3, string elsa4Key, string elsa3Default, string? whenBound = null) =>
        new(elsa3, Elsa3MemberKind.Input, Elsa3MemberRuleKind.DefaultFlip, elsa4Key, Literal(elsa3Default), WhenBound: whenBound);

    /// <summary>R2 for an Elsa 4 member Elsa 3 does not have: always emit the Elsa 3 behaviour.</summary>
    private static Elsa3MemberRule Synthetic(string elsa4Key, string value) =>
        new(elsa4Key, Elsa3MemberKind.Synthetic, Elsa3MemberRuleKind.DefaultFlip, elsa4Key, Literal(value));

    /// <summary>R3: removed only when absent or equal to the default (null means absent, null or empty).</summary>
    private static Elsa3MemberRule Removed(string elsa3, string? elsa3Default = null, Elsa3MemberKind kind = Elsa3MemberKind.Input, string? warning = null) =>
        new(elsa3, kind, Elsa3MemberRuleKind.RemovedInput, null, Literal(elsa3Default), BehaviourWarning: warning);

    /// <summary>R4: removed when nothing captures it; captured is unconvertible unless an exact projection exists.</summary>
    private static Elsa3MemberRule Lost(string elsa3, string? projection = null) =>
        new(elsa3, Elsa3MemberKind.Output, Elsa3MemberRuleKind.LostOutput, Projection: projection);

    /// <summary>R5: converted only when the value provably fits the narrower contract.</summary>
    private static Elsa3MemberRule Narrow(string elsa3, string elsa4Key, Elsa3ValueContract contract, string? elsa3Default = null) =>
        new(elsa3, Elsa3MemberKind.Input, Elsa3MemberRuleKind.NarrowedContract, elsa4Key,
            elsa3Default is null ? null : Literal(elsa3Default), contract);

    /// <summary>R7: structure generated by the entry's rewrite, which also decides when its warning applies.</summary>
    private static Elsa3MemberRule Structure(string elsa3, Elsa3MemberKind kind = Elsa3MemberKind.Property, string? warning = null) =>
        new(elsa3, kind, Elsa3MemberRuleKind.Structure, BehaviourWarning: warning);

    /// <summary>R8: graph-level data, applied by graph conversion (spec 239), not by member rules.</summary>
    private static Elsa3MemberRule Graph(string elsa3, Elsa3MemberKind kind = Elsa3MemberKind.Property) =>
        new(elsa3, kind, Elsa3MemberRuleKind.GraphLevel);

    /// <summary>R6 for a use: the member must equal <paramref name="required"/> (null: absent or null), else no counterpart.</summary>
    private static Elsa3MemberRule UseRestriction(string elsa3, string? required, Elsa3MemberKind kind = Elsa3MemberKind.Port) =>
        new(elsa3, kind, Elsa3MemberRuleKind.UseRestriction, null, Literal(required));

    /// <summary>A captured output whose Elsa 4 counterpart means something else.</summary>
    private static Elsa3MemberRule SemanticsChanged(string elsa3) =>
        new(elsa3, Elsa3MemberKind.Output, Elsa3MemberRuleKind.SemanticsChanged);

    /// <summary><c>customProperties.canStartWorkflow</c> carried to the Elsa 4 input of that name.</summary>
    private static Elsa3MemberRule CanStartWorkflowCarried() =>
        new("CanStartWorkflow", Elsa3MemberKind.CustomProperty, Elsa3MemberRuleKind.Carry, "CanStartWorkflow");

    /// <summary><c>customProperties.canStartWorkflow</c> on a start-only trigger: <c>true</c> is required (a mid-flow wait is R6).</summary>
    private static Elsa3MemberRule StartOnly() =>
        UseRestriction("CanStartWorkflow", "true", Elsa3MemberKind.CustomProperty);

    /// <summary>Null (spec 267): Elsa 3 ran with a value Elsa 4's default equals.</summary>
    private static Elsa3NullConversion NullUnbound => new(Elsa3NullRule.NoBinding);

    /// <summary>Null (spec 267): Elsa 3 ran with null, which the Elsa 4 input accepts.</summary>
    private static Elsa3NullConversion NullAsNull => new(Elsa3NullRule.TypedNull);

    /// <summary>Null (spec 267): Elsa 3 ran with <paramref name="value"/>, which Elsa 4's default differs from.</summary>
    private static Elsa3NullConversion NullEmits(string value) => new(Elsa3NullRule.Emit, value);

    /// <summary>Null (spec 267): Elsa 4 cannot reproduce or represent what Elsa 3 did.</summary>
    private static Elsa3NullConversion NullRefused(string reason, string? whenBound = null) =>
        new(Elsa3NullRule.Refuse, Reason: reason, WhenBound: whenBound);

    /// <summary>Null (spec 267): Elsa 3 rejected the activity as missing a required input.</summary>
    private static Elsa3NullConversion NullRequired => NullRefused("Elsa 3 rejects the activity without it.");

    private static Elsa3OutcomeRule Outcome(string elsa3, params string[] elsa4) => new(elsa3, elsa4);

    private static Elsa3OutcomeRule UnsupportedOutcome(string elsa3, string reason) => new(elsa3, [], reason);

    private static JsonElement Literal(string? value) =>
        value is null ? JsonSerializer.SerializeToElement<string?>(null) : JsonSerializer.SerializeToElement(value);
}
