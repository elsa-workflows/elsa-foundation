using Elsa.Workflows.Design.CodeGeneration;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace Elsa.Workflows.Design.CodeGeneration.Tests;

public sealed class ActivityCallGeneratorTests
{
    [Fact]
    public void Generator_emits_deterministic_named_facade_and_typed_call_handle()
    {
        const string source = $$"""
            using Elsa.Workflows.Design.CodeGeneration;

            {{AuthoringStubs}}

            namespace GeneratorConsumer
            {
                public sealed record ChargeCardResult(bool Approved, string ReceiptId);

                [ActivityCall("ChargeCard", "payments.charge-card@2", typeof(ChargeCardResult))]
                [ActivityInput("customerId", "customer-id", typeof(string), 0)]
                [ActivityInput("amount", "amount", typeof(decimal), 1)]
                [ActivityOutput("Approved", "approved", typeof(bool))]
                [ActivityOutput("ReceiptId", "receipt-id", typeof(string))]
                [ActivityOutcome("Completed", "completed")]
                [ActivityOutcome("Declined", "declined")]
                public sealed class ChargeCard;
            }
            """;

        var first = RunGenerator(source);
        var second = RunGenerator(source);
        var firstSource = GetFacadeSource(first);
        var secondSource = GetFacadeSource(second);

        Assert.Equal(firstSource, secondSource);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            namespace Elsa.Workflows.Design.CodeGeneration.Generated;

            public static partial class ActivityCallExtensions
            {
                public static ChargeCardCall ChargeCard(
                    this global::Elsa.Workflows.Design.Core.Authoring.ISequenceBuilder sequence,
                    global::Elsa.Workflows.Design.Core.Authoring.ActivityArgument<string> customerId,
                    global::Elsa.Workflows.Design.Core.Authoring.ActivityArgument<decimal> amount)
                {
                    if (sequence is null)
                        throw new global::System.ArgumentNullException(nameof(sequence));

                    var call = sequence.Add<global::GeneratorConsumer.ChargeCard, global::GeneratorConsumer.ChargeCardResult>(
                        "payments.charge-card@2",
                        inputs =>
                        {
                            inputs.Set("customer-id", customerId);
                            inputs.Set("amount", amount);
                        });
                    return new ChargeCardCall(call);
                }
            }

            public sealed class ChargeCardCall
            {
                private readonly global::Elsa.Workflows.Design.Core.Authoring.ActivityCall<global::GeneratorConsumer.ChargeCardResult> _call;

                internal ChargeCardCall(global::Elsa.Workflows.Design.Core.Authoring.ActivityCall<global::GeneratorConsumer.ChargeCardResult> call)
                {
                    _call = call;
                    Outputs = new ChargeCardOutputSources(call);
                    Outcomes = new ChargeCardOutcomeSources(call);
                }

                public global::Elsa.Workflows.Design.Core.Authoring.ActivityNodeHandle Node => _call.Node;
                public global::Elsa.Workflows.Design.Core.Authoring.ActivityResultSource<global::GeneratorConsumer.ChargeCardResult> Result => _call.Result;
                public ChargeCardOutputSources Outputs { get; }
                public ChargeCardOutcomeSources Outcomes { get; }
            }

            public sealed class ChargeCardOutputSources
            {
                private readonly global::Elsa.Workflows.Design.Core.Authoring.ActivityCall<global::GeneratorConsumer.ChargeCardResult> _call;

                internal ChargeCardOutputSources(global::Elsa.Workflows.Design.Core.Authoring.ActivityCall<global::GeneratorConsumer.ChargeCardResult> call) => _call = call;

                public global::Elsa.Workflows.Design.Core.Authoring.ActivityResultSource<bool> Approved => _call.Output<bool>("approved");

                public global::Elsa.Workflows.Design.Core.Authoring.ActivityResultSource<string> ReceiptId => _call.Output<string>("receipt-id");
            }

            public sealed class ChargeCardOutcomeSources
            {
                private readonly global::Elsa.Workflows.Design.Core.Authoring.ActivityCall<global::GeneratorConsumer.ChargeCardResult> _call;

                internal ChargeCardOutcomeSources(global::Elsa.Workflows.Design.Core.Authoring.ActivityCall<global::GeneratorConsumer.ChargeCardResult> call) => _call = call;

                public global::Elsa.Workflows.Design.Core.Authoring.ActivityOutcomeSource Completed => _call.Outcome("completed");

                public global::Elsa.Workflows.Design.Core.Authoring.ActivityOutcomeSource Declined => _call.Outcome("declined");
            }
            """.ReplaceLineEndings("\n") + "\n",
            firstSource);
        Assert.DoesNotContain(first.OutputCompilation.GetDiagnostics(), diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
    }

    [Fact]
    public void Generator_reports_duplicate_method_names_with_stable_diagnostic()
    {
        const string source = """
            using Elsa.Workflows.Design.CodeGeneration;

            namespace GeneratorConsumer;

            [ActivityCall("Send", "mail.send@1", typeof(string))]
            public sealed class SendMail;

            [ActivityCall("Send", "sms.send@1", typeof(string))]
            public sealed class SendSms;
            """;

        var result = RunGenerator(source);
        var diagnostic = GetSingleGeneratorDiagnostic(result);

        Assert.Equal(ActivityCallGenerator.DuplicateFacadeDiagnosticId, diagnostic.Id);
        Assert.Equal(
            "Activity-call method 'Send' is declared by both 'GeneratorConsumer.SendMail' and 'GeneratorConsumer.SendSms'. Method names must be unique.",
            diagnostic.GetMessage());
        Assert.DoesNotContain(result.RunResult.Results.SelectMany(x => x.GeneratedSources), source => source.HintName == ActivityCallGenerator.GeneratedHintName);
    }

    [Fact]
    public void Generator_reports_unsupported_generic_activity_shape_with_stable_diagnostic()
    {
        const string source = """
            using Elsa.Workflows.Design.CodeGeneration;

            namespace GeneratorConsumer;

            [ActivityCall("Map", "collections.map@1", typeof(string))]
            public sealed class Map<T>;
            """;

        var result = RunGenerator(source);
        var diagnostic = GetSingleGeneratorDiagnostic(result);

        Assert.Equal(ActivityCallGenerator.UnsupportedShapeDiagnosticId, diagnostic.Id);
        Assert.Equal(
            "Activity 'GeneratorConsumer.Map<T>' has unsupported activity-call metadata: activity types must be top-level and non-generic",
            diagnostic.GetMessage());
    }

    [Fact]
    public void Generator_discovers_activity_metadata_from_referenced_assemblies()
    {
        const string activityPackage = """
            namespace Elsa.Workflows.Design.CodeGeneration
            {
                [System.AttributeUsage(System.AttributeTargets.Class)]
                public sealed class ActivityCallAttribute(string methodName, string activityVersionId, System.Type resultType) : System.Attribute;

                [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true)]
                public sealed class ActivityInputAttribute(string name, string key, System.Type type, int order, bool isRequired = true) : System.Attribute;

                [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true)]
                public sealed class ActivityOutputAttribute(string name, string key, System.Type type) : System.Attribute;

                [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true)]
                public sealed class ActivityOutcomeAttribute(string name, string key) : System.Attribute;
            }

            namespace ReferencedActivities
            {
                using Elsa.Workflows.Design.CodeGeneration;

                public sealed record SendEmailResult(string MessageId);

                [ActivityCall("SendEmail", "messaging.send-email@1", typeof(SendEmailResult))]
                [ActivityInput("to", "to", typeof(string), 0)]
                [ActivityOutput("MessageId", "message-id", typeof(string))]
                [ActivityOutcome("Sent", "sent")]
                public sealed class SendEmail;
            }
            """;
        var activityReference = CompileReference("ReferencedActivityPackage", activityPackage);
        var result = RunGenerator(AuthoringStubs, [activityReference]);
        var generated = GetFacadeSource(result);

        Assert.Contains("public static SendEmailCall SendEmail(", generated, StringComparison.Ordinal);
        Assert.Contains("sequence.Add<global::ReferencedActivities.SendEmail, global::ReferencedActivities.SendEmailResult>", generated, StringComparison.Ordinal);
        Assert.DoesNotContain(result.OutputCompilation.GetDiagnostics(), diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
    }

    private static GeneratorResult RunGenerator(string source, IReadOnlyCollection<MetadataReference>? additionalReferences = null)
    {
        var compilation = CSharpCompilation.Create(
            assemblyName: "GeneratorConsumer",
            syntaxTrees: [CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview))],
            references: GetPlatformReferences().Concat(additionalReferences ?? []),
            options: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));

        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            generators: [new ActivityCallGenerator().AsSourceGenerator()],
            parseOptions: new CSharpParseOptions(LanguageVersion.Preview));
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var updatedCompilation, out var diagnostics);

        Assert.DoesNotContain(diagnostics, diagnostic => diagnostic.Id == "CS8785");
        return new GeneratorResult(driver.GetRunResult(), updatedCompilation);
    }

    private static MetadataReference CompileReference(string assemblyName, string source)
    {
        var compilation = CSharpCompilation.Create(
            assemblyName,
            [CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview))],
            GetPlatformReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        using var stream = new MemoryStream();
        var emit = compilation.Emit(stream);
        Assert.True(emit.Success, string.Join(Environment.NewLine, emit.Diagnostics));
        return MetadataReference.CreateFromImage(stream.ToArray());
    }

    private static string GetFacadeSource(GeneratorResult result) => result.RunResult.Results
        .SelectMany(x => x.GeneratedSources)
        .Single(x => x.HintName == ActivityCallGenerator.GeneratedHintName)
        .SourceText
        .ToString()
        .ReplaceLineEndings("\n");

    private static Diagnostic GetSingleGeneratorDiagnostic(GeneratorResult result)
    {
        var exception = result.RunResult.Diagnostics.FirstOrDefault(diagnostic => diagnostic.Id == "CS8785");
        Assert.True(exception is null, exception?.ToString());
        return Assert.Single(result.RunResult.Diagnostics);
    }

    private static IReadOnlyCollection<MetadataReference> GetPlatformReferences()
    {
        var trustedPlatformAssemblies = (string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ?? string.Empty;
        return trustedPlatformAssemblies
            .Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries)
            .Select(path => MetadataReference.CreateFromFile(path))
            .ToArray();
    }

    private sealed record GeneratorResult(GeneratorDriverRunResult RunResult, Compilation OutputCompilation);

    private const string AuthoringStubs = """
        namespace Elsa.Workflows.Design.Core.Authoring
        {
            public interface ISequenceBuilder
            {
                ActivityCall<TResult> Add<TActivity, TResult>(string activityVersionId, System.Action<IActivityInputBuilder<TActivity>>? inputs = null, string? nodeId = null);
            }

            public interface IActivityInputBuilder<TActivity>
            {
                IActivityInputBuilder<TActivity> Set<T>(string inputKey, ActivityArgument<T> argument);
            }

            public readonly struct ActivityArgument<T>;
            public sealed record ActivityNodeHandle(string NodeId);
            public sealed record ActivityOutcomeSource(ActivityNodeHandle Node, string OutcomeKey);
            public sealed class ActivityResultSource<T>;

            public sealed class ActivityCall<TResult>
            {
                public ActivityNodeHandle Node { get; } = new("node");
                public ActivityResultSource<TResult> Result { get; } = new();
                public ActivityResultSource<T> Output<T>(string projectionKey) => new();
                public ActivityOutcomeSource Outcome(string outcomeKey) => new(Node, outcomeKey);
            }
        }
        """;
}
