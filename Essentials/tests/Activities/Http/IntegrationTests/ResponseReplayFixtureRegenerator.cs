namespace Elsa.Activities.Http.IntegrationTests;

/// <summary>
/// Regenerates the captured response-replay closures in place after a change to the value type model, so they match
/// what publishing produces today. Before Elsa 4's first stable release a format change updates stored fixtures in place
/// instead of adding a compatibility shim. The authored workflow, its node order, bindings and the External response
/// profile are kept; what the type model derives is brought up to date with the host's own code:
/// <list type="bullet">
/// <item>type aliases read as the host reads them (spec 1228: <c>Object</c> is the dynamic kind <c>Any</c>);</item>
/// <item>a dictionary or list of arrays, stored under an array alias such as <c>System.String[]</c>, names its nested
/// element (spec 1228 US5), as <see cref="TypeReferenceFactory.FromClrType"/> describes the CLR type;</item>
/// <item>a projection or conversion plan whose type changed gets the representation
/// <see cref="ValueRepresentationDefaults.Infer"/> gives it, and each plan its own fingerprint;</item>
/// <item>each artifact gets the hash and id the host's hasher computes, and the manifests the new identities, closure
/// SHA-256 and byte length.</item>
/// </list>
/// </summary>
/// <remarks>
/// Opt-in, never run by CI. Run it once from the repository root when <see cref="ResponseReplaySafetyProcessTests"/>
/// fails after a type-model change (a pinned-identity mismatch such as "Value conversion plan fingerprint does not match
/// its pinned contents", or the publication comparison), then re-run that test class and commit the four changed
/// fixture files:
/// <code>
/// ELSA_REGENERATE_RESPONSE_REPLAY_FIXTURES=1 dotnet test Essentials/tests/Activities/Http/IntegrationTests --filter "FullyQualifiedName~ResponseReplayFixtureRegenerator"
/// </code>
/// It is idempotent: on fixtures that already match it changes nothing.
/// </remarks>
public sealed class ResponseReplayFixtureRegenerator
{
    private const string EnableVariable = "ELSA_REGENERATE_RESPONSE_REPLAY_FIXTURES";

    // The closures the runtime imports today. Order matters: the second manifest also records the first closure's
    // identities as its baseline.
    private static readonly string[] Prefixes = ["current-format-external", "http-sync-default-external"];

    private static readonly JsonSerializerOptions TypeOptions = new(JsonSerializerDefaults.Web)
    {
        Converters = { new JsonStringEnumConverter() },
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull
    };

    [Fact]
    public async Task Regenerate()
    {
        if (Environment.GetEnvironmentVariable(EnableVariable) != "1")
            return;

        var directory = Path.Combine(FindRepositoryRoot(),
            "Essentials", "tests", "Activities", "Http", "Fixtures", "ResponseReplayHost", "Fixtures");
        await using var serializerServices = await CreateSerializerServicesAsync();
        var payloadSerializer = serializerServices.GetRequiredService<IPayloadSerializer>();
        var serializer = new WorkflowArtifactClosureSerializer(payloadSerializer);
        await using var host = WorkflowExecutionHarness.Create().Build("response-replay-fixture-regenerator");
        var hasher = host.Services.GetRequiredService<IWorkflowExecutableHasher>();
        var replacements = new Dictionary<string, string>(StringComparer.Ordinal);
        var lengths = new Dictionary<string, (int From, int To)>(StringComparer.Ordinal);

        foreach (var prefix in Prefixes)
        {
            var closurePath = Path.Combine(directory, $"{prefix}-closure.json");
            var bytes = await File.ReadAllBytesAsync(closurePath);
            var root = JsonNode.Parse(bytes)!;
            Assert.True(Encoding.UTF8.GetBytes(root.ToJsonString()).AsSpan().SequenceEqual(bytes),
                $"{prefix}: the closure does not round-trip through JsonNode, so it cannot be regenerated byte-stably.");

            UpgradeTypeModel(root, payloadSerializer, replacements);

            // The artifacts' identities are what the host's hasher computes for the regenerated contents; the closure names
            // them in more than one place (the identity, the root artifact id), so every occurrence follows.
            var closure = serializer.Deserialize(root.ToJsonString())!;
            var identities = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var artifact in closure.Artifacts)
            {
                var hash = hasher.ComputeHash(artifact.RootActivity, artifact.InputContract!, artifact.Dependencies,
                    artifact.PersistenceMode, artifact.WorkflowVariables, artifact.IncidentStrategy);
                Add(identities, artifact.Identity.ArtifactHash, hash);
                Add(identities, artifact.Identity.ArtifactId, hasher.CreateArtifactId("artifact-", hash));
            }

            foreach (var (oldIdentity, newIdentity) in identities)
                replacements[oldIdentity] = newIdentity;
            var updated = Encoding.UTF8.GetBytes(identities.Aggregate(root.ToJsonString(),
                (current, pair) => current.Replace(pair.Key, pair.Value, StringComparison.Ordinal)));
            var (from, to) = (Sha256(bytes), Sha256(updated));
            Add(replacements, from, to);
            lengths[to] = (bytes.Length, updated.Length);
            if (!bytes.AsSpan().SequenceEqual(updated))
                await File.WriteAllBytesAsync(closurePath, updated);
        }

        foreach (var prefix in Prefixes)
        {
            var manifestPath = Path.Combine(directory, $"{prefix}-manifest.json");
            var text = await File.ReadAllTextAsync(manifestPath);
            var updated = replacements.Aggregate(text, (current, pair) => current.Replace(pair.Key, pair.Value, StringComparison.Ordinal));
            // The byte length recorded next to a closure SHA-256 follows the regenerated closure.
            foreach (var (sha, (from, to)) in lengths)
                updated = Regex.Replace(updated,
                    $"\"byteLength\": {from},(\\s*)\"sha256\": \"{sha}\"",
                    match => $"\"byteLength\": {to},{match.Groups[1].Value}\"sha256\": \"{sha}\"");
            if (!StringComparer.Ordinal.Equals(text, updated))
                await File.WriteAllTextAsync(manifestPath, updated, new UTF8Encoding(text.Length > 0 && text[0] == '﻿'));
        }

        // The regenerated closures import: every pinned identity verifies.
        foreach (var prefix in Prefixes)
        {
            var closure = serializer.Deserialize(await File.ReadAllTextAsync(Path.Combine(directory, $"{prefix}-closure.json")))!;
            Assert.All(closure.Artifacts, artifact => Assert.True(hasher.MatchesHash(artifact), artifact.Identity.ArtifactId));
        }
    }

    /// <summary>Brings every type, representation and plan fingerprint in a closure up to the current type model.</summary>
    private static bool UpgradeTypeModel(JsonNode? node, IPayloadSerializer payloadSerializer, Dictionary<string, string> replacements)
    {
        switch (node)
        {
            case JsonObject value:
            {
                var changed = UpgradeType(value);
                var typeChanged = false;
                foreach (var (name, child) in value.ToList())
                {
                    var childChanged = UpgradeTypeModel(child, payloadSerializer, replacements);
                    changed |= childChanged;
                    if (name is "sourceType" || (name is "type" && !value.ContainsKey("sourceType")))
                        typeChanged = childChanged;
                }

                // A projection (type) or plan (sourceType) whose own type changed takes the representation inferred for it.
                if (typeChanged && value["sourceRepresentation"] is JsonValue && (value["sourceType"] ?? value["type"]) is JsonObject type &&
                    type.ContainsKey("alias"))
                    value["sourceRepresentation"] = ValueRepresentationDefaults.Infer(type.Deserialize<ValueTypeDescriptor>(TypeOptions)!).ToString();

                // A plan's fingerprint is derived from its contents: read without it, the plan computes the current one.
                if (value["fingerprint"] is JsonValue fingerprint && value.ContainsKey("sourceType") && value.ContainsKey("targetType"))
                {
                    value.Remove("fingerprint");
                    var current = value.Deserialize<ValueConversionPlan>(TypeOptions)!.Fingerprint;
                    value["fingerprint"] = current;
                    changed |= !StringComparer.Ordinal.Equals(fingerprint.GetValue<string>(), current);
                }

                // So is an activity contract's schema fingerprint: the contract built from its parts computes the current one.
                if (value["schemaFingerprint"] is JsonValue schemaFingerprint && value.ContainsKey("activityTypeKey"))
                {
                    var current = ContractFingerprint(value, payloadSerializer);
                    value["schemaFingerprint"] = current;
                    // The manifests record the response contract's fingerprint.
                    Add(replacements, schemaFingerprint.GetValue<string>(), current);
                    changed |= !StringComparer.Ordinal.Equals(schemaFingerprint.GetValue<string>(), current);
                }

                return changed;
            }
            case JsonArray array:
                return array.Aggregate(false, (changed, child) => UpgradeTypeModel(child, payloadSerializer, replacements) | changed);
            default:
                return false;
        }
    }

    private static string ContractFingerprint(JsonObject contract, IPayloadSerializer payloadSerializer)
    {
        // The fixtures' contracts carry no background or undeclared-variable flags; the public constructor covers them.
        Assert.False(contract.ContainsKey("supportsBackgroundExecution") || contract.ContainsKey("accessesUndeclaredVariables"));
        T Read<T>(JsonNode? node) => (T)payloadSerializer.Deserialize(node!.ToJsonString(), typeof(T));
        return new ActivityContract(
            contract["activityTypeKey"]!.GetValue<string>(),
            contract["contractVersion"]!.GetValue<string>(),
            contract["descriptorKind"]!.GetValue<string>(),
            JsonSerializer.SerializeToElement(contract["descriptorPayload"]),
            contract["inputs"]!.AsObject().Select(input => Read<ActivityInputContract>(input.Value)).ToArray(),
            Read<ActivityResultContract>(contract["result"]),
            contract["outcomes"]!.AsArray().Select(outcome => outcome!.GetValue<string>()).ToArray(),
            Read<ActivityActivationRequirement>(contract["activation"]),
            contract["sideEffectProfile"] is { } profile ? Enum.Parse<SideEffectProfile>(profile.GetValue<string>()) : SideEffectProfile.External)
            .SchemaFingerprint;
    }

    // A type reference ({ alias, collectionKind, element }) or a value-store type ({ kind, schema: { Alias } }).
    private static bool UpgradeType(JsonObject value)
    {
        var changed = false;
        if (value["alias"] is JsonValue alias && alias.TryGetValue<string>(out var stored) && value.ContainsKey("collectionKind"))
        {
            var read = TypeAliasConvention.ReadAlias(stored);
            if (read.EndsWith("[]", StringComparison.Ordinal) && !value.ContainsKey("element") &&
                Type.GetType(read) is { } arrayType &&
                Enum.Parse<CollectionKind>(value["collectionKind"]!.GetValue<string>()) is var kind && kind != CollectionKind.Single)
            {
                var reference = TypeReferenceFactory.FromClrType(TypeReferenceFactory.Close(arrayType, kind), TypeAliasConvention.CanonicalAlias);
                var nested = JsonSerializer.SerializeToNode(reference, TypeOptions)!.AsObject();
                value["alias"] = reference.Alias;
                value["element"] = nested["element"]!.DeepClone();
                changed = true;
            }
            else if (!StringComparer.Ordinal.Equals(stored, read))
            {
                value["alias"] = read;
                changed = true;
            }
        }

        if (value["kind"] is JsonValue kindValue && kindValue.TryGetValue<string>(out var storedKind) &&
            value["schema"] is JsonObject schema && schema["Alias"] is JsonValue schemaAlias &&
            schemaAlias.TryGetValue<string>(out var storedSchemaAlias))
        {
            var readKind = TypeAliasConvention.ReadAlias(storedKind);
            var readSchemaAlias = TypeAliasConvention.ReadAlias(storedSchemaAlias);
            if (!StringComparer.Ordinal.Equals(storedKind, readKind) || !StringComparer.Ordinal.Equals(storedSchemaAlias, readSchemaAlias))
            {
                value["kind"] = readKind;
                schema["Alias"] = readSchemaAlias;
                changed = true;
            }
        }

        return changed;
    }

    private static void Add(Dictionary<string, string> replacements, string from, string to)
    {
        if (StringComparer.Ordinal.Equals(from, to))
            return;
        Assert.Equal(from.Length, to.Length);
        if (replacements.TryGetValue(from, out var existing))
            Assert.Equal(existing, to);
        replacements[from] = to;
    }

    private static string Sha256(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();

    private static async Task<ServiceProvider> CreateSerializerServicesAsync()
    {
        var services = new ServiceCollection();
        services.AddLogging();
        new Elsa.Events.EventsFeature().ConfigureServices(services);
        new Elsa.Serialization.SystemText.SerializationFeature().ConfigureServices(services);
        var provider = services.BuildServiceProvider();
        foreach (var task in provider.GetServices<IStartupTask>())
            await task.ExecuteAsync(CancellationToken.None);
        return provider;
    }

    private static string FindRepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !Directory.Exists(Path.Combine(directory.FullName, ".git")) && !File.Exists(Path.Combine(directory.FullName, ".git")))
            directory = directory.Parent;
        return directory?.FullName ?? throw new InvalidOperationException("The repository root was not found.");
    }
}
